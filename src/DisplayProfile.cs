using System;
using System.Collections.Generic;
using System.Drawing;
using System.Linq;

namespace DeskFences
{
    /// <summary>
    /// Manages per-display-topology layout profiles so switching between large screens, small laptop
    /// screens, and multi-monitor setups preserves each topology's fence geometry, member icon slots,
    /// and loose desktop icon positions without destructive overwriting.
    /// </summary>
    internal static class DisplayProfileManager
    {
        private const int MaxAutoGeneratedProfiles = 8;

        internal static Rectangle[] NormalizeAreas(Rectangle[] areas)
        {
            if (areas == null || areas.Length == 0) return new Rectangle[0];
            return areas
                .Where(a => a.Width >= 3 && a.Height >= 3)
                .OrderBy(a => a.Left)
                .ThenBy(a => a.Top)
                .ThenBy(a => a.Width)
                .ThenBy(a => a.Height)
                .ToArray();
        }

        internal static string BuildProfileKey(Rectangle[] areas)
        {
            var sorted = NormalizeAreas(areas);
            if (sorted.Length == 0) return "";
            return string.Join("|", sorted.Select(a =>
                string.Format("{0},{1},{2}x{3}", a.Left, a.Top, a.Width, a.Height)));
        }

        internal static string BuildProfileLabel(Rectangle[] areas)
        {
            var sorted = NormalizeAreas(areas);
            if (sorted.Length == 0) return "未知屏幕";
            if (sorted.Length == 1)
                return string.Format("单屏 {0}×{1}", sorted[0].Width, sorted[0].Height);
            return string.Format("{0}屏 ({1})", sorted.Length,
                string.Join(" + ", sorted.Select(a => string.Format("{0}×{1}", a.Width, a.Height))));
        }

        internal static Rectangle[] GetProfileAreas(DisplayProfile profile)
        {
            if (profile == null || profile.Areas == null || profile.Areas.Count == 0)
                return new Rectangle[0];
            return NormalizeAreas(profile.Areas.Select(a => a.ToRectangle()).ToArray());
        }

        internal static DisplayProfile FindMatchingProfile(AppConfig config, Rectangle[] targetAreas)
        {
            if (config == null || config.DisplayProfiles == null || config.DisplayProfiles.Count == 0)
                return null;
            var sorted = NormalizeAreas(targetAreas);
            if (sorted.Length == 0) return null;

            string exactKey = BuildProfileKey(sorted);
            DisplayProfile exact;
            if (config.DisplayProfiles.TryGetValue(exactKey, out exact) && exact != null)
                return exact;

            // Fuzzy match within +/-1 cell per monitor edge/size to absorb minor grid origin or taskbar
            // rounding without merging genuinely different screen sizes, orientations, or DPI scales.
            DisplayProfile best = null;
            int bestDiff = int.MaxValue;
            foreach (var candidate in config.DisplayProfiles.Values)
            {
                if (candidate == null) continue;
                var candAreas = GetProfileAreas(candidate);
                if (candAreas.Length != sorted.Length) continue;

                int totalDiff = 0;
                bool ok = true;
                for (int i = 0; i < sorted.Length; i++)
                {
                    int dl = Math.Abs(candAreas[i].Left - sorted[i].Left);
                    int dt = Math.Abs(candAreas[i].Top - sorted[i].Top);
                    int dw = Math.Abs(candAreas[i].Width - sorted[i].Width);
                    int dh = Math.Abs(candAreas[i].Height - sorted[i].Height);
                    if (dl > 1 || dt > 1 || dw > 1 || dh > 1)
                    {
                        ok = false;
                        break;
                    }
                    totalDiff += dl + dt + dw + dh;
                }
                if (!ok) continue;

                bool better = best == null
                    || totalDiff < bestDiff
                    || (totalDiff == bestDiff && !candidate.AutoGenerated && best.AutoGenerated)
                    || (totalDiff == bestDiff && candidate.AutoGenerated == best.AutoGenerated && candidate.LastUsedUtcTicks > best.LastUsedUtcTicks);
                if (better)
                {
                    best = candidate;
                    bestDiff = totalDiff;
                }
            }
            return best;
        }

        /// <summary>
        /// Snapshots current fence geometry, member relative slots, and loose desktop icon cells into
        /// the profile matching <paramref name="areas"/>. Returns true if persisted profile data changed.
        /// </summary>
        internal static bool CaptureCurrentProfile(
            AppConfig config,
            Rectangle[] areas,
            IEnumerable<DesktopIconInfo> icons,
            DesktopGridMetrics metrics,
            bool markUserEdited)
        {
            if (config == null) return false;
            var sorted = NormalizeAreas(areas);
            if (sorted.Length == 0) return false;

            if (config.DisplayProfiles == null)
                config.DisplayProfiles = new Dictionary<string, DisplayProfile>(StringComparer.OrdinalIgnoreCase);

            bool changed = false;
            DisplayProfile profile = FindMatchingProfile(config, sorted);
            if (profile == null)
            {
                string key = BuildProfileKey(sorted);
                profile = new DisplayProfile
                {
                    Key = key,
                    Label = BuildProfileLabel(sorted),
                    Areas = sorted.Select(MonitorGridSnapshot.FromRectangle).ToList(),
                    AutoGenerated = !markUserEdited,
                    LastUsedUtcTicks = DateTime.UtcNow.Ticks
                };
                config.DisplayProfiles[key] = profile;
                changed = true;
            }
            else
            {
                if (markUserEdited && profile.AutoGenerated)
                {
                    profile.AutoGenerated = false;
                    changed = true;
                }
                string label = BuildProfileLabel(sorted);
                if (!string.Equals(profile.Label, label, StringComparison.Ordinal))
                {
                    profile.Label = label;
                    changed = true;
                }
                if (profile.Areas == null || profile.Areas.Count != sorted.Length)
                {
                    profile.Areas = sorted.Select(MonitorGridSnapshot.FromRectangle).ToList();
                    changed = true;
                }
                profile.LastUsedUtcTicks = DateTime.UtcNow.Ticks;
            }

            if (!string.Equals(config.ActiveProfileKey, profile.Key, StringComparison.OrdinalIgnoreCase))
            {
                config.ActiveProfileKey = profile.Key;
                changed = true;
            }

            var liveFenceIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var ownerMap = new Dictionary<string, FenceConfig>(StringComparer.OrdinalIgnoreCase);
            foreach (var fc in config.Fences)
            {
                liveFenceIds.Add(fc.Id);
                foreach (var mid in fc.MemberIconIds)
                    ownerMap[mid] = fc;

                FenceProfileLayout fl;
                if (!profile.Fences.TryGetValue(fc.Id, out fl) || fl == null)
                {
                    fl = new FenceProfileLayout();
                    profile.Fences[fc.Id] = fl;
                    changed = true;
                }
                if (fl.OuterCol != fc.OuterCol || fl.OuterRow != fc.OuterRow ||
                    fl.OuterCols != fc.OuterCols || fl.OuterRows != fc.OuterRows)
                {
                    fl.OuterCol = fc.OuterCol;
                    fl.OuterRow = fc.OuterRow;
                    fl.OuterCols = fc.OuterCols;
                    fl.OuterRows = fc.OuterRows;
                    changed = true;
                }
                // Prune slots for icons that are no longer members of this fence
                var memberSet = new HashSet<string>(fc.MemberIconIds, StringComparer.OrdinalIgnoreCase);
                foreach (string staleId in fl.MemberSlots.Keys.Where(k => !memberSet.Contains(k)).ToArray())
                {
                    fl.MemberSlots.Remove(staleId);
                    changed = true;
                }
            }

            // Remove deleted fences from this profile
            foreach (string staleFence in profile.Fences.Keys.Where(k => !liveFenceIds.Contains(k)).ToArray())
            {
                profile.Fences.Remove(staleFence);
                changed = true;
            }

            if (icons != null && metrics.CellWidth > 0 && metrics.CellHeight > 0)
            {
                var presentLoose = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                foreach (var ic in icons)
                {
                    if (string.IsNullOrEmpty(ic.Identity)) continue;
                    int col = ic.GridCol(metrics);
                    int row = ic.GridRow(metrics);

                    FenceConfig owner;
                    if (ownerMap.TryGetValue(ic.Identity, out owner))
                    {
                        // Remove from loose icons if icon was dragged into a fence
                        if (profile.LooseIcons.Remove(ic.Identity))
                            changed = true;

                        if (owner.IsInInnerRect(col, row))
                        {
                            var fl = profile.Fences[owner.Id];
                            int relCol = col - (owner.OuterCol + 1);
                            int relRow = row - (owner.OuterRow + 1);
                            CellOffset existing;
                            if (!fl.MemberSlots.TryGetValue(ic.Identity, out existing) ||
                                existing == null || existing.Col != relCol || existing.Row != relRow)
                            {
                                fl.MemberSlots[ic.Identity] = new CellOffset { Col = relCol, Row = relRow };
                                changed = true;
                            }
                        }
                    }
                    else
                    {
                        presentLoose.Add(ic.Identity);
                        // Only record loose icons that are outside all fences and inside a valid monitor area
                        bool insideAnyFence = config.Fences.Any(f => f.IsInOuterRect(col, row));
                        bool insideAnyArea = sorted.Any(a => a.Contains(col, row));
                        if (!insideAnyFence && insideAnyArea)
                        {
                            CellOffset existing;
                            if (!profile.LooseIcons.TryGetValue(ic.Identity, out existing) ||
                                existing == null || existing.Col != col || existing.Row != row)
                            {
                                profile.LooseIcons[ic.Identity] = new CellOffset { Col = col, Row = row };
                                changed = true;
                            }
                        }
                    }
                }

                // Clean up loose entries for icons that became fence members (keep temporarily absent files
                // only if they aren't owned; deleted files are harmlessly small, or prune if > 500)
                foreach (string ownedId in ownerMap.Keys)
                {
                    if (profile.LooseIcons.Remove(ownedId))
                        changed = true;
                }
            }

            PruneAutoGeneratedProfiles(config, profile.Key);
            return changed;
        }

        private static DisplayProfile SelectSourceProfile(AppConfig config, string excludeKey)
        {
            if (config == null || config.DisplayProfiles == null || config.DisplayProfiles.Count == 0)
                return null;

            // 1. Prefer the currently active profile if it was user-edited
            DisplayProfile active;
            if (!string.IsNullOrEmpty(config.ActiveProfileKey) &&
                !string.Equals(config.ActiveProfileKey, excludeKey, StringComparison.OrdinalIgnoreCase) &&
                config.DisplayProfiles.TryGetValue(config.ActiveProfileKey, out active) &&
                active != null && !active.AutoGenerated && GetProfileAreas(active).Length > 0)
            {
                return active;
            }

            // 2. Otherwise prefer the most recently used user-edited profile (avoids deriving from temporary odd resolutions)
            DisplayProfile bestUser = config.DisplayProfiles.Values
                .Where(p => p != null && !p.AutoGenerated &&
                            !string.Equals(p.Key, excludeKey, StringComparison.OrdinalIgnoreCase) &&
                            GetProfileAreas(p).Length > 0)
                .OrderByDescending(p => p.LastUsedUtcTicks)
                .FirstOrDefault();
            if (bestUser != null) return bestUser;

            // 3. Fallback to most recent profile with valid areas
            return config.DisplayProfiles.Values
                .Where(p => p != null &&
                            !string.Equals(p.Key, excludeKey, StringComparison.OrdinalIgnoreCase) &&
                            GetProfileAreas(p).Length > 0)
                .OrderByDescending(p => p.LastUsedUtcTicks)
                .FirstOrDefault();
        }

        /// <summary>
        /// Switches <paramref name="config"/> to the saved DisplayProfile matching <paramref name="targetAreas"/>,
        /// or proportionally adapts a new DisplayProfile from the best source profile without mutating any
        /// other stored display profiles.
        /// </summary>
        internal static DisplayProfile SwitchOrAdaptProfile(
            AppConfig config,
            Rectangle[] targetAreas,
            DesktopGridMetrics metrics,
            float dpi,
            out bool createdNewProfile)
        {
            createdNewProfile = false;
            var sortedTarget = NormalizeAreas(targetAreas);
            if (config == null || sortedTarget.Length == 0) return null;

            if (config.DisplayProfiles == null)
                config.DisplayProfiles = new Dictionary<string, DisplayProfile>(StringComparer.OrdinalIgnoreCase);

            DisplayProfile existing = FindMatchingProfile(config, sortedTarget);
            if (existing != null)
            {
                ApplyKnownProfile(config, existing, sortedTarget, metrics, dpi);
                existing.LastUsedUtcTicks = DateTime.UtcNow.Ticks;
                config.ActiveProfileKey = existing.Key;
                return existing;
            }

            // First time seeing this display topology: derive proportionally from the best existing profile!
            createdNewProfile = true;
            DisplayProfile source = SelectSourceProfile(config, null);
            DisplayProfile adapted = BuildAdaptedProfile(config, source, sortedTarget, metrics, dpi);
            config.DisplayProfiles[adapted.Key] = adapted;
            config.ActiveProfileKey = adapted.Key;
            PruneAutoGeneratedProfiles(config, adapted.Key);
            return adapted;
        }

        private static void ApplyKnownProfile(
            AppConfig config,
            DisplayProfile profile,
            Rectangle[] targetAreas,
            DesktopGridMetrics metrics,
            float dpi)
        {
            var sourceForNewFences = SelectSourceProfile(config, profile.Key);
            var sourceAreas = GetProfileAreas(sourceForNewFences);
            var placed = new List<FenceConfig>();
            var newlyCreated = new List<FenceConfig>();

            var liveIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var fc in config.Fences)
            {
                liveIds.Add(fc.Id);
                FenceProfileLayout saved;
                if (profile.Fences.TryGetValue(fc.Id, out saved) && saved != null)
                {
                    fc.OuterCol = saved.OuterCol;
                    fc.OuterRow = saved.OuterRow;
                    fc.OuterCols = Math.Max(3, saved.OuterCols);
                    fc.OuterRows = Math.Max(3, saved.OuterRows);
                    placed.Add(fc);
                }
                else
                {
                    newlyCreated.Add(fc);
                }
            }

            foreach (string staleId in profile.Fences.Keys.Where(k => !liveIds.Contains(k)).ToArray())
                profile.Fences.Remove(staleId);

            // Fit existing saved fences first (usually a no-op unless fuzzy +/-1 cell clipped an edge)
            FenceManager.FitExistingFences(placed, targetAreas, metrics, dpi);

            // Place any fence that was created while on another screen without disturbing existing saved fences
            foreach (var fc in newlyCreated)
            {
                FenceProfileLayout srcLayout = null;
                if (sourceForNewFences != null)
                    sourceForNewFences.Fences.TryGetValue(fc.Id, out srcLayout);

                Rectangle fitted = MapSingleFenceToTarget(fc, srcLayout, sourceAreas, placed, targetAreas, metrics, dpi);
                fc.OuterCol = fitted.X;
                fc.OuterRow = fitted.Y;
                fc.OuterCols = fitted.Width;
                fc.OuterRows = fitted.Height;
                placed.Add(fc);

                var adaptedLayout = new FenceProfileLayout
                {
                    OuterCol = fc.OuterCol,
                    OuterRow = fc.OuterRow,
                    OuterCols = fc.OuterCols,
                    OuterRows = fc.OuterRows,
                    MemberSlots = AdaptMemberSlots(fc, srcLayout != null ? srcLayout.MemberSlots : null, fc.OuterCols, fc.OuterRows)
                };
                profile.Fences[fc.Id] = adaptedLayout;
            }

            // Keep saved geometry in sync if FitExistingFences adjusted a fuzzy edge
            foreach (var fc in placed)
            {
                FenceProfileLayout fl;
                if (profile.Fences.TryGetValue(fc.Id, out fl) && fl != null)
                {
                    fl.OuterCol = fc.OuterCol;
                    fl.OuterRow = fc.OuterRow;
                    fl.OuterCols = fc.OuterCols;
                    fl.OuterRows = fc.OuterRows;
                }
            }
        }

        private static DisplayProfile BuildAdaptedProfile(
            AppConfig config,
            DisplayProfile source,
            Rectangle[] targetAreas,
            DesktopGridMetrics metrics,
            float dpi)
        {
            string key = BuildProfileKey(targetAreas);
            var adapted = new DisplayProfile
            {
                Key = key,
                Label = BuildProfileLabel(targetAreas),
                Areas = targetAreas.Select(MonitorGridSnapshot.FromRectangle).ToList(),
                AutoGenerated = true,
                LastUsedUtcTicks = DateTime.UtcNow.Ticks
            };

            Rectangle[] sourceAreas = GetProfileAreas(source);
            var placed = new List<FenceConfig>();

            // Map fences in deterministic visual order (top-left to bottom-right) so layout feels cohesive
            var orderedFences = config.Fences
                .OrderBy(fc =>
                {
                    FenceProfileLayout sl;
                    return (source != null && source.Fences.TryGetValue(fc.Id, out sl) && sl != null) ? sl.OuterRow : fc.OuterRow;
                })
                .ThenBy(fc =>
                {
                    FenceProfileLayout sl;
                    return (source != null && source.Fences.TryGetValue(fc.Id, out sl) && sl != null) ? sl.OuterCol : fc.OuterCol;
                })
                .ToList();

            foreach (var fc in orderedFences)
            {
                FenceProfileLayout srcLayout = null;
                if (source != null) source.Fences.TryGetValue(fc.Id, out srcLayout);

                Rectangle fitted = MapSingleFenceToTarget(fc, srcLayout, sourceAreas, placed, targetAreas, metrics, dpi);
                fc.OuterCol = fitted.X;
                fc.OuterRow = fitted.Y;
                fc.OuterCols = fitted.Width;
                fc.OuterRows = fitted.Height;
                placed.Add(fc);

                adapted.Fences[fc.Id] = new FenceProfileLayout
                {
                    OuterCol = fc.OuterCol,
                    OuterRow = fc.OuterRow,
                    OuterCols = fc.OuterCols,
                    OuterRows = fc.OuterRows,
                    MemberSlots = AdaptMemberSlots(fc, srcLayout != null ? srcLayout.MemberSlots : null, fc.OuterCols, fc.OuterRows)
                };
            }

            // Proportionally adapt loose desktop icons from source profile (staying outside all fences)
            if (source != null && source.LooseIcons != null && source.LooseIcons.Count > 0)
            {
                var occupied = new HashSet<long>();
                var memberIds = new HashSet<string>(
                    config.Fences.SelectMany(f => f.MemberIconIds),
                    StringComparer.OrdinalIgnoreCase);

                var orderedLoose = source.LooseIcons
                    .Where(kv => kv.Value != null && !memberIds.Contains(kv.Key))
                    .OrderBy(kv => kv.Value.Row)
                    .ThenBy(kv => kv.Value.Col)
                    .ToList();

                foreach (var kv in orderedLoose)
                {
                    Point desiredCell;
                    Rectangle preferredTarget;
                    MapPointToTargetGrid(kv.Value.Col, kv.Value.Row, sourceAreas, targetAreas, out desiredCell, out preferredTarget);

                    Point placedCell;
                    if (FindNearestFreeOutsideCellPreferArea(config.Fences, desiredCell, preferredTarget, targetAreas, metrics, occupied, out placedCell))
                    {
                        occupied.Add(CellKey(placedCell.X, placedCell.Y));
                        adapted.LooseIcons[kv.Key] = new CellOffset { Col = placedCell.X, Row = placedCell.Y };
                    }
                }
            }

            return adapted;
        }

        private static Rectangle MapSingleFenceToTarget(
            FenceConfig fc,
            FenceProfileLayout srcLayout,
            Rectangle[] sourceAreas,
            List<FenceConfig> alreadyPlaced,
            Rectangle[] targetAreas,
            DesktopGridMetrics metrics,
            float dpi)
        {
            int srcCol = srcLayout != null ? srcLayout.OuterCol : fc.OuterCol;
            int srcRow = srcLayout != null ? srcLayout.OuterRow : fc.OuterRow;
            int srcCols = Math.Max(3, srcLayout != null ? srcLayout.OuterCols : fc.OuterCols);
            int srcRows = Math.Max(3, srcLayout != null ? srcLayout.OuterRows : fc.OuterRows);
            int memberCount = fc.MemberIconIds.Count;

            // Choose target monitor & normalized anchor (uX, uY)
            Rectangle dstArea = targetAreas[0];
            double uX = 0.0, uY = 0.0;
            bool hasRelative = false;

            if (sourceAreas != null && sourceAreas.Length > 0)
            {
                Rectangle srcRef;
                if (sourceAreas.Length == targetAreas.Length)
                {
                    int idx = FindContainingOrNearestAreaIndex(sourceAreas, new Rectangle(srcCol, srcRow, srcCols, srcRows));
                    srcRef = sourceAreas[idx];
                    dstArea = targetAreas[idx];
                }
                else if (sourceAreas.Length > targetAreas.Length)
                {
                    // Multi -> Fewer/Single (Strategy A): map across source union bounding box so
                    // left-monitor fences converge left and right-monitor fences converge right!
                    srcRef = UnionAreas(sourceAreas);
                    if (targetAreas.Length == 1)
                    {
                        dstArea = targetAreas[0];
                    }
                    else
                    {
                        double fracX = Clamp01((srcCol + srcCols * 0.5 - srcRef.Left) / Math.Max(1.0, srcRef.Width));
                        int targetIdx = Math.Min(targetAreas.Length - 1, (int)Math.Floor(fracX * targetAreas.Length));
                        dstArea = targetAreas[targetIdx];
                    }
                }
                else
                {
                    // Single -> Multi: keep existing fences on the matching/primary monitor
                    int srcIdx = FindContainingOrNearestAreaIndex(sourceAreas, new Rectangle(srcCol, srcRow, srcCols, srcRows));
                    srcRef = sourceAreas[srcIdx];
                    dstArea = FindClosestAreaByOrigin(targetAreas, srcRef);
                }

                int srcSpanX = Math.Max(0, srcRef.Width - srcCols);
                int srcSpanY = Math.Max(0, srcRef.Height - srcRows);
                uX = srcSpanX > 0 ? Clamp01((srcCol - srcRef.Left) / (double)srcSpanX) : 0.5;
                uY = srcSpanY > 0 ? Clamp01((srcRow - srcRef.Top) / (double)srcSpanY) : 0.5;
                hasRelative = true;
            }

            // Keep original fence size whenever it fits comfortably on dstArea; only shrink/reshape if oversized
            int dstCols = Math.Min(srcCols, dstArea.Width);
            int dstRows = Math.Min(srcRows, dstArea.Height);
            dstCols = Math.Max(3, Math.Min(dstArea.Width, dstCols));
            dstRows = Math.Max(3, Math.Min(dstArea.Height, dstRows));

            if ((long)(dstCols - 2) * (dstRows - 2) < memberCount &&
                (long)(dstArea.Width - 2) * (dstArea.Height - 2) >= memberCount)
            {
                // Reshape wide <-> tall on smaller / rotated screens to preserve full member capacity
                dstRows = Math.Min(dstArea.Height, Math.Max(dstRows, 2 + (int)Math.Ceiling((double)memberCount / Math.Max(1, dstCols - 2))));
                dstCols = Math.Min(dstArea.Width, Math.Max(dstCols, 2 + (int)Math.Ceiling((double)memberCount / Math.Max(1, dstRows - 2))));
            }

            int desiredCol, desiredRow;
            if (hasRelative)
            {
                int dstSpanX = Math.Max(0, dstArea.Width - dstCols);
                int dstSpanY = Math.Max(0, dstArea.Height - dstRows);
                desiredCol = dstArea.Left + (int)Math.Round(uX * dstSpanX);
                desiredRow = dstArea.Top + (int)Math.Round(uY * dstSpanY);
                // Preserve intentional 1-cell outer margin (e.g. Windows left desktop icon column) when space allows
                if (uX > 0.0 && desiredCol == dstArea.Left && dstSpanX >= 2)
                    desiredCol = dstArea.Left + 1;
                if (uY > 0.0 && desiredRow == dstArea.Top && dstSpanY >= 2)
                    desiredRow = dstArea.Top + 1;
            }
            else
            {
                desiredCol = srcCol;
                desiredRow = srcRow;
            }

            // Try preferred target monitor first so proportional screen placement stays intuitive,
            // then fall back to all target monitors if preferred monitor is crowded.
            Rectangle fitted = FindFittingOnAreas(alreadyPlaced, new[] { dstArea }, new Point(desiredCol, desiredRow),
                new Size(dstCols, dstRows), metrics, dpi, memberCount);
            if (fitted.IsEmpty && targetAreas.Length > 1)
            {
                fitted = FindFittingOnAreas(alreadyPlaced, targetAreas, new Point(desiredCol, desiredRow),
                    new Size(dstCols, dstRows), metrics, dpi, memberCount);
            }
            if (fitted.IsEmpty)
            {
                // Extreme small screen where total capacity cannot avoid overlap: clamp safely inside dstArea
                // without deleting the fence or discarding any MemberIconIds!
                Point clamped = MonitorGrid.ClampOrigin(dstArea, new Point(desiredCol, desiredRow), new Size(dstCols, dstRows));
                fitted = new Rectangle(clamped.X, clamped.Y, dstCols, dstRows);
            }
            return fitted;
        }

        private static Rectangle FindFittingOnAreas(
            IEnumerable<FenceConfig> placed,
            Rectangle[] areas,
            Point desired,
            Size size,
            DesktopGridMetrics metrics,
            float dpi,
            int memberCount)
        {
            if (size.Width < 3 || size.Height < 3) return Rectangle.Empty;
            bool found;
            Point origin = FenceManager.FindNearestNonOverlappingOrigin(
                placed, null, desired.X, desired.Y, size.Width, size.Height,
                desired.X, desired.Y, areas, metrics, dpi, out found);
            if (found) return new Rectangle(origin, size);

            // Search for a non-overlapping resized rectangle that preserves capacity first (or max capacity possible)
            Rectangle best = Rectangle.Empty;
            int bestCap = -1;
            int maxW = Math.Min(size.Width, areas.Max(a => a.Width));
            int maxH = Math.Min(Math.Max(size.Height, 2 + (int)Math.Ceiling(memberCount / 1.0)), areas.Max(a => a.Height));

            for (int w = maxW; w >= 3; w--)
            {
                int minNeededH = Math.Max(3, 2 + (int)Math.Ceiling((double)Math.Max(memberCount, bestCap + 1) / Math.Max(1, w - 2)));
                int hi = Math.Min(maxH, Math.Max(size.Height, minNeededH));
                for (int h = hi; h >= 3; h--)
                {
                    int cap = (w - 2) * (h - 2);
                    if (cap <= bestCap) break;
                    origin = FenceManager.FindNearestNonOverlappingOrigin(
                        placed, null, desired.X, desired.Y, w, h, desired.X, desired.Y, areas, metrics, dpi, out found);
                    if (found)
                    {
                        best = new Rectangle(origin.X, origin.Y, w, h);
                        bestCap = cap;
                        break;
                    }
                }
            }
            return best;
        }

        internal static Dictionary<string, CellOffset> AdaptMemberSlots(
            FenceConfig fence,
            Dictionary<string, CellOffset> sourceSlots,
            int targetOuterCols,
            int targetOuterRows)
        {
            var result = new Dictionary<string, CellOffset>(StringComparer.OrdinalIgnoreCase);
            if (fence == null || fence.MemberIconIds.Count == 0) return result;

            int innerCols = Math.Max(1, targetOuterCols - 2);
            int innerRows = Math.Max(1, targetOuterRows - 2);
            var used = new HashSet<long>();
            var needPack = new List<string>();

            // Preserve exact (RelCol, RelRow) for every member whose saved slot still fits!
            foreach (string id in fence.MemberIconIds)
            {
                CellOffset slot;
                if (sourceSlots != null && sourceSlots.TryGetValue(id, out slot) && slot != null &&
                    slot.Col >= 0 && slot.Col < innerCols && slot.Row >= 0 && slot.Row < innerRows &&
                    used.Add(CellKey(slot.Col, slot.Row)))
                {
                    result[id] = new CellOffset { Col = slot.Col, Row = slot.Row };
                }
                else
                {
                    needPack.Add(id);
                }
            }

            // Pack remaining members in their original visual reading order (RelRow, RelCol)
            needPack.Sort((a, b) =>
            {
                CellOffset sa = null, sb = null;
                if (sourceSlots != null) { sourceSlots.TryGetValue(a, out sa); sourceSlots.TryGetValue(b, out sb); }
                int ra = sa != null ? sa.Row : int.MaxValue;
                int rb = sb != null ? sb.Row : int.MaxValue;
                if (ra != rb) return ra.CompareTo(rb);
                int ca = sa != null ? sa.Col : int.MaxValue;
                int cb = sb != null ? sb.Col : int.MaxValue;
                if (ca != cb) return ca.CompareTo(cb);
                return StringComparer.OrdinalIgnoreCase.Compare(a, b);
            });

            foreach (string id in needPack)
            {
                bool assigned = false;
                for (int r = 0; r < innerRows && !assigned; r++)
                {
                    for (int c = 0; c < innerCols; c++)
                    {
                        if (used.Add(CellKey(c, r)))
                        {
                            result[id] = new CellOffset { Col = c, Row = r };
                            assigned = true;
                            break;
                        }
                    }
                }
                // If inner capacity is exhausted on an ultra-tiny screen, leave unassigned in this profile
                // while keeping the icon safely in fence.MemberIconIds so it returns on larger screens!
            }

            return result;
        }

        /// <summary>
        /// Plans exact collision-free grid cells for every live desktop icon (both fence members and
        /// loose desktop icons) according to <paramref name="profile"/>, returning the atomic client-position
        /// moves needed to bring Explorer's desktop into exact sync.
        /// </summary>
        internal static List<KeyValuePair<string, Point>> PlanIconRestoration(
            AppConfig config,
            DisplayProfile profile,
            List<DesktopIconInfo> liveIcons,
            Rectangle[] targetAreas,
            DesktopGridMetrics metrics,
            out Dictionary<string, Point> targetCells)
        {
            targetCells = new Dictionary<string, Point>(StringComparer.OrdinalIgnoreCase);
            var moves = new List<KeyValuePair<string, Point>>();
            if (config == null || liveIcons == null || liveIcons.Count == 0 ||
                metrics.CellWidth <= 0 || metrics.CellHeight <= 0)
                return moves;

            var sortedAreas = NormalizeAreas(targetAreas);
            if (sortedAreas.Length == 0) return moves;

            var iconById = new Dictionary<string, DesktopIconInfo>(StringComparer.OrdinalIgnoreCase);
            foreach (var ic in liveIcons)
            {
                if (!string.IsNullOrEmpty(ic.Identity))
                    iconById[ic.Identity] = ic;
            }

            var ownerMap = new Dictionary<string, FenceConfig>(StringComparer.OrdinalIgnoreCase);
            foreach (var fc in config.Fences)
            {
                foreach (var mid in fc.MemberIconIds)
                    ownerMap[mid] = fc;
            }

            var occupied = new HashSet<long>();
            var overflowMembers = new List<DesktopIconInfo>();

            // Pass 1: Place every fence's members into their exact saved relative inner slots
            foreach (var fc in config.Fences)
            {
                FenceProfileLayout fl = null;
                if (profile != null && profile.Fences != null)
                    profile.Fences.TryGetValue(fc.Id, out fl);
                var savedSlots = fl != null ? fl.MemberSlots : null;

                var membersPresent = new List<DesktopIconInfo>();
                foreach (string mid in fc.MemberIconIds)
                {
                    DesktopIconInfo ic;
                    if (iconById.TryGetValue(mid, out ic))
                        membersPresent.Add(ic);
                }

                // Deterministic order: members with saved slots first (by row, col), then newly added members
                membersPresent.Sort((a, b) =>
                {
                    CellOffset sa = null, sb = null;
                    if (savedSlots != null) { savedSlots.TryGetValue(a.Identity, out sa); savedSlots.TryGetValue(b.Identity, out sb); }
                    bool ha = sa != null, hb = sb != null;
                    if (ha != hb) return ha ? -1 : 1;
                    if (ha)
                    {
                        if (sa.Row != sb.Row) return sa.Row.CompareTo(sb.Row);
                        if (sa.Col != sb.Col) return sa.Col.CompareTo(sb.Col);
                    }
                    return StringComparer.OrdinalIgnoreCase.Compare(a.Identity, b.Identity);
                });

                foreach (var ic in membersPresent)
                {
                    Point chosenCell = Point.Empty;
                    bool placed = false;

                    CellOffset slot;
                    if (savedSlots != null && savedSlots.TryGetValue(ic.Identity, out slot) && slot != null)
                    {
                        int absCol = fc.OuterCol + 1 + slot.Col;
                        int absRow = fc.OuterRow + 1 + slot.Row;
                        if (fc.IsInInnerRect(absCol, absRow) && occupied.Add(CellKey(absCol, absRow)))
                        {
                            chosenCell = new Point(absCol, absRow);
                            placed = true;
                        }
                    }

                    if (!placed)
                    {
                        // New member (e.g. dragged in on another screen) or slot out of bounds -> pack cleanly inside fence
                        for (int r = fc.OuterRow + 1; r < fc.OuterRow + fc.OuterRows - 1 && !placed; r++)
                        {
                            for (int c = fc.OuterCol + 1; c < fc.OuterCol + fc.OuterCols - 1; c++)
                            {
                                if (occupied.Add(CellKey(c, r)))
                                {
                                    chosenCell = new Point(c, r);
                                    placed = true;
                                    break;
                                }
                            }
                        }
                    }

                    if (placed)
                    {
                        targetCells[ic.Identity] = chosenCell;
                    }
                    else
                    {
                        // Extreme tiny-screen overflow: place safely outside fences in Pass 2 without dropping membership!
                        overflowMembers.Add(ic);
                    }
                }
            }

            // Pass 2: Place all loose (non-fence) desktop icons + any tiny-screen overflow members
            var loosePresent = new List<DesktopIconInfo>();
            foreach (var ic in liveIcons)
            {
                if (!string.IsNullOrEmpty(ic.Identity) && !ownerMap.ContainsKey(ic.Identity))
                    loosePresent.Add(ic);
            }

            var savedLoose = (profile != null && profile.LooseIcons != null) ? profile.LooseIcons : null;
            loosePresent.Sort((a, b) =>
            {
                CellOffset sa = null, sb = null;
                if (savedLoose != null) { savedLoose.TryGetValue(a.Identity, out sa); savedLoose.TryGetValue(b.Identity, out sb); }
                bool ha = sa != null, hb = sb != null;
                if (ha != hb) return ha ? -1 : 1;
                if (ha)
                {
                    if (sa.Row != sb.Row) return sa.Row.CompareTo(sb.Row);
                    if (sa.Col != sb.Col) return sa.Col.CompareTo(sb.Col);
                }
                int ar = a.GridRow(metrics), br = b.GridRow(metrics);
                if (ar != br) return ar.CompareTo(br);
                return a.GridCol(metrics).CompareTo(b.GridCol(metrics));
            });

            foreach (var ic in loosePresent.Concat(overflowMembers))
            {
                int curCol = ic.GridCol(metrics);
                int curRow = ic.GridRow(metrics);
                Point desiredCell = new Point(curCol, curRow);
                CellOffset saved = null;
                bool hasSaved = savedLoose != null && !ownerMap.ContainsKey(ic.Identity) &&
                                savedLoose.TryGetValue(ic.Identity, out saved) && saved != null;
                if (hasSaved)
                    desiredCell = new Point(saved.Col, saved.Row);

                bool desiredValid = sortedAreas.Any(a => a.Contains(desiredCell)) &&
                                    !config.Fences.Any(f => f.IsInOuterRect(desiredCell.X, desiredCell.Y)) &&
                                    !occupied.Contains(CellKey(desiredCell.X, desiredCell.Y));

                Point chosen;
                if (desiredValid)
                {
                    chosen = desiredCell;
                    occupied.Add(CellKey(chosen.X, chosen.Y));
                }
                else
                {
                    Rectangle prefArea = sortedAreas[FindContainingOrNearestAreaIndex(sortedAreas, new Rectangle(desiredCell.X, desiredCell.Y, 1, 1))];
                    if (FindNearestFreeOutsideCellPreferArea(config.Fences, desiredCell, prefArea, sortedAreas, metrics, occupied, out chosen))
                    {
                        occupied.Add(CellKey(chosen.X, chosen.Y));
                    }
                    else
                    {
                        chosen = new Point(curCol, curRow);
                    }
                }
                targetCells[ic.Identity] = chosen;
            }

            // Compute minimal client-position deltas only for icons that actually need to move
            foreach (var ic in liveIcons)
            {
                Point dstCell;
                if (string.IsNullOrEmpty(ic.Identity) || !targetCells.TryGetValue(ic.Identity, out dstCell))
                    continue;
                int curCol = ic.GridCol(metrics);
                int curRow = ic.GridRow(metrics);
                if (dstCell.X == curCol && dstCell.Y == curRow) continue;

                int tx = ic.ClientPosition.X + (dstCell.X - curCol) * metrics.CellWidth;
                int ty = ic.ClientPosition.Y + (dstCell.Y - curRow) * metrics.CellHeight;
                moves.Add(new KeyValuePair<string, Point>(ic.Identity, new Point(tx, ty)));
            }

            return moves;
        }

        private static void MapPointToTargetGrid(
            int srcCol, int srcRow,
            Rectangle[] sourceAreas,
            Rectangle[] targetAreas,
            out Point desiredCell,
            out Rectangle preferredTarget)
        {
            preferredTarget = targetAreas[0];
            if (sourceAreas == null || sourceAreas.Length == 0)
            {
                desiredCell = new Point(srcCol, srcRow);
                return;
            }

            Rectangle srcRef;
            if (sourceAreas.Length == targetAreas.Length)
            {
                int idx = FindContainingOrNearestAreaIndex(sourceAreas, new Rectangle(srcCol, srcRow, 1, 1));
                srcRef = sourceAreas[idx];
                preferredTarget = targetAreas[idx];
            }
            else if (sourceAreas.Length > targetAreas.Length)
            {
                srcRef = UnionAreas(sourceAreas);
                if (targetAreas.Length == 1)
                {
                    preferredTarget = targetAreas[0];
                }
                else
                {
                    double fracX = Clamp01((srcCol + 0.5 - srcRef.Left) / Math.Max(1.0, srcRef.Width));
                    int idx = Math.Min(targetAreas.Length - 1, (int)Math.Floor(fracX * targetAreas.Length));
                    preferredTarget = targetAreas[idx];
                }
            }
            else
            {
                int idx = FindContainingOrNearestAreaIndex(sourceAreas, new Rectangle(srcCol, srcRow, 1, 1));
                srcRef = sourceAreas[idx];
                preferredTarget = FindClosestAreaByOrigin(targetAreas, srcRef);
            }

            double uX = Clamp01((srcCol - srcRef.Left) / (double)Math.Max(1, srcRef.Width - 1));
            double uY = Clamp01((srcRow - srcRef.Top) / (double)Math.Max(1, srcRef.Height - 1));
            int col = preferredTarget.Left + (int)Math.Round(uX * Math.Max(0, preferredTarget.Width - 1));
            int row = preferredTarget.Top + (int)Math.Round(uY * Math.Max(0, preferredTarget.Height - 1));
            desiredCell = new Point(col, row);
        }

        private static bool FindNearestFreeOutsideCellPreferArea(
            IEnumerable<FenceConfig> fences,
            Point desiredCell,
            Rectangle preferredArea,
            Rectangle[] allAreas,
            DesktopGridMetrics metrics,
            HashSet<long> occupied,
            out Point bestCell)
        {
            Point refPt = new Point(
                metrics.OriginX + (int)Math.Round((desiredCell.X + 0.5) * Math.Max(1, metrics.CellWidth)),
                metrics.OriginY + (int)Math.Round((desiredCell.Y + 0.5) * Math.Max(1, metrics.CellHeight)));

            if (FenceManager.FindNearestFreeOutsideCell(fences, refPt, new[] { preferredArea }, metrics, occupied, out bestCell))
                return true;
            if (allAreas != null && allAreas.Length > 1)
                return FenceManager.FindNearestFreeOutsideCell(fences, refPt, allAreas, metrics, occupied, out bestCell);
            bestCell = Point.Empty;
            return false;
        }

        private static void PruneAutoGeneratedProfiles(AppConfig config, string keepKey)
        {
            if (config == null || config.DisplayProfiles == null) return;
            var autoKeys = config.DisplayProfiles.Values
                .Where(p => p != null && p.AutoGenerated && !string.Equals(p.Key, keepKey, StringComparison.OrdinalIgnoreCase))
                .OrderByDescending(p => p.LastUsedUtcTicks)
                .Skip(MaxAutoGeneratedProfiles)
                .Select(p => p.Key)
                .ToArray();
            foreach (string k in autoKeys)
                config.DisplayProfiles.Remove(k);
        }

        private static int FindContainingOrNearestAreaIndex(Rectangle[] areas, Rectangle rect)
        {
            int bestIdx = 0;
            double bestDistSq = double.MaxValue;
            double rcx = rect.Left + rect.Width * 0.5;
            double rcy = rect.Top + rect.Height * 0.5;
            for (int i = 0; i < areas.Length; i++)
            {
                if (areas[i].IntersectsWith(rect)) return i;
                double cx = Math.Max(areas[i].Left, Math.Min(areas[i].Right, rcx));
                double cy = Math.Max(areas[i].Top, Math.Min(areas[i].Bottom, rcy));
                double dx = rcx - cx, dy = rcy - cy;
                double d2 = dx * dx + dy * dy;
                if (d2 < bestDistSq)
                {
                    bestDistSq = d2;
                    bestIdx = i;
                }
            }
            return bestIdx;
        }

        private static Rectangle FindClosestAreaByOrigin(Rectangle[] candidates, Rectangle reference)
        {
            Rectangle best = candidates[0];
            double bestScore = double.MaxValue;
            foreach (var c in candidates)
            {
                double dx = c.Left - reference.Left;
                double dy = c.Top - reference.Top;
                double dw = c.Width - reference.Width;
                double dh = c.Height - reference.Height;
                double score = dx * dx + dy * dy + (dw * dw + dh * dh) * 0.25;
                if (score < bestScore)
                {
                    bestScore = score;
                    best = c;
                }
            }
            return best;
        }

        private static Rectangle UnionAreas(Rectangle[] areas)
        {
            Rectangle u = areas[0];
            for (int i = 1; i < areas.Length; i++)
                u = Rectangle.Union(u, areas[i]);
            return u;
        }

        private static double Clamp01(double v)
        {
            return v < 0.0 ? 0.0 : (v > 1.0 ? 1.0 : v);
        }

        private static long CellKey(int col, int row)
        {
            return (((long)col) << 32) | (uint)row;
        }
    }
