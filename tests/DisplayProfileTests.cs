        private const BindingFlags Instance = BindingFlags.NonPublic | BindingFlags.Instance;

        private static void Check(bool ok, string message)
        {
            if (!ok) throw new InvalidOperationException(message);
        }

        private static DesktopIconInfo MakeIcon(string id, int col, int row, DesktopGridMetrics m, int index = 0)
        {
            int px = m.OriginX + col * m.CellWidth;
            int py = m.OriginY + row * m.CellHeight;
            return new DesktopIconInfo
            {
                Index = index,
                Identity = id,
                ParsingName = @"C:\Desktop\" + id + ".txt",
                Name = id,
                ClientPosition = new Point(px, py),
                ScreenBounds = new Rectangle(px, py, 72, 86),
                IconBounds = new Rectangle(px + 12, py + 4, 48, 48),
                LabelBounds = new Rectangle(px, py + 54, 72, 30)
            };
        }

        private static void CheckLargeSmallRoundTripAndLooseIcons(string dir)
        {
            var m = new DesktopGridMetrics { CellWidth = 96, CellHeight = 120, OriginX = 2, OriginY = 2 };
            var largeAreas = new[] { new Rectangle(0, 0, 26, 13) };
            var smallAreas = new[] { new Rectangle(0, 0, 14, 8) };

            var cfg = new AppConfig();
            // Two fences on large screen: left-upper & right-lower
            var fLeft = new FenceConfig
            {
                Id = "fence-left", Title = "常用", OuterCol = 1, OuterRow = 1, OuterCols = 6, OuterRows = 5,
                MemberIconIds = new List<string> { "m1", "m2", "m3" }
            };
            var fRight = new FenceConfig
            {
                Id = "fence-right", Title = "日志", OuterCol = 18, OuterRow = 6, OuterCols = 7, OuterRows = 5,
                MemberIconIds = new List<string> { "r1", "r2", "r3", "r4" }
            };
            cfg.Fences.Add(fLeft);
            cfg.Fences.Add(fRight);

            // Specific member relative slots + 3 loose desktop icons (left edge, bottom-right, top-center)
            var largeIcons = new List<DesktopIconInfo>
            {
                MakeIcon("m1", 2, 2, m, 0), // rel (0, 0) in fLeft
                MakeIcon("m2", 4, 2, m, 1), // rel (2, 0) in fLeft (intentional gap!)
                MakeIcon("m3", 3, 4, m, 2), // rel (1, 2) in fLeft
                MakeIcon("r1", 19, 7, m, 3), // rel (0, 0) in fRight
                MakeIcon("r2", 22, 7, m, 4), // rel (3, 0) in fRight
                MakeIcon("r3", 20, 9, m, 5), // rel (1, 2) in fRight
                MakeIcon("r4", 23, 9, m, 6), // rel (4, 2) in fRight
                MakeIcon("loose-left", 0, 0, m, 7),
                MakeIcon("loose-br", 25, 12, m, 8),
                MakeIcon("loose-top", 12, 0, m, 9),
            };

            Check(DisplayProfileManager.CaptureCurrentProfile(cfg, largeAreas, largeIcons, m, true),
                "Initial capture of large-screen profile must record layout.");
            string largeKey = cfg.ActiveProfileKey;
            Check(cfg.DisplayProfiles.ContainsKey(largeKey) && !cfg.DisplayProfiles[largeKey].AutoGenerated,
                "Captured baseline profile must be marked user-edited.");

            // 1. First switch to small screen (14x8): must proportionally adapt BOTH fences and loose icons without overwriting large profile!
            bool createdSmall;
            var smallProf = DisplayProfileManager.SwitchOrAdaptProfile(cfg, smallAreas, m, 1f, out createdSmall);
            Check(createdSmall && smallProf != null && smallProf.AutoGenerated,
                "First visit to small screen must create an auto-generated profile.");
            Check(smallAreas[0].Contains(new Rectangle(fLeft.OuterCol, fLeft.OuterRow, fLeft.OuterCols, fLeft.OuterRows)) &&
                  smallAreas[0].Contains(new Rectangle(fRight.OuterCol, fRight.OuterRow, fRight.OuterCols, fRight.OuterRows)),
                "Adapted fences must fit completely inside small screen.");
            Check(!FenceManager.ZonesOverlap(fLeft.OuterCol, fLeft.OuterRow, fLeft.OuterCols, fLeft.OuterRows,
                fRight.OuterCol, fRight.OuterRow, fRight.OuterCols, fRight.OuterRows, m, 1f),
                "Adapted fences on small screen must not overlap.");
            Check(fRight.OuterCol > fLeft.OuterCol,
                "Right-side fence on large screen must remain to the right of left-side fence on small screen.");

            // Simulate Explorer scrambling every icon to (0,0..9) on switch, then plan restoration on small screen!
            var scrambledOnSmall = largeIcons.Select((ic, idx) => MakeIcon(ic.Identity, 0, idx % 8, m, idx)).ToList();
            Dictionary<string, Point> smallTargets;
            DisplayProfileManager.PlanIconRestoration(cfg, smallProf, scrambledOnSmall, smallAreas, m, out smallTargets);
            Check(fLeft.MemberIconIds.All(id => fLeft.IsInInnerRect(smallTargets[id].X, smallTargets[id].Y)),
                "All fLeft members must be restored inside fLeft on small screen.");
            Check(fRight.MemberIconIds.All(id => fRight.IsInInnerRect(smallTargets[id].X, smallTargets[id].Y)),
                "All fRight members must be restored inside fRight on small screen.");
            // Verify loose icons stay outside all fences, distinct, and roughly preserve relative screen anchors!
            var smallLooseIds = new[] { "loose-left", "loose-br", "loose-top" };
            foreach (string lid in smallLooseIds)
            {
                Point p = smallTargets[lid];
                Check(smallAreas[0].Contains(p) && !fLeft.IsInOuterRect(p.X, p.Y) && !fRight.IsInOuterRect(p.X, p.Y),
                    "Adapted loose icon " + lid + " must land inside small screen and outside all fences. Got " + p);
            }
            Check(smallTargets["loose-left"].X <= 2 && smallTargets["loose-left"].Y <= 2,
                "Top-left loose icon must adapt near top-left on small screen. Got " + smallTargets["loose-left"]);
            Check(smallTargets["loose-br"].X >= 8 && smallTargets["loose-br"].Y >= 5,
                "Bottom-right loose icon must adapt near bottom-right on small screen. Got " + smallTargets["loose-br"]);
            Check(smallTargets.Values.Distinct().Count() == smallTargets.Count,
                "Every icon on small screen must receive a unique collision-free cell.");

            // User tweaks small screen layout and adds a new member "m4" to fLeft while on small screen!
            fLeft.OuterCol = 0; fLeft.OuterRow = 0;
            fLeft.MemberIconIds.Add("m4");
            var smallLiveAfterEdit = smallTargets.Select((kv, idx) => MakeIcon(kv.Key, kv.Value.X, kv.Value.Y, m, idx)).ToList();
            smallLiveAfterEdit.Add(MakeIcon("m4", fLeft.OuterCol + 1, fLeft.OuterRow + 1, m, 99));
            DisplayProfileManager.CaptureCurrentProfile(cfg, smallAreas, smallLiveAfterEdit, m, true);
            Check(!smallProf.AutoGenerated, "User edit on small screen must promote small profile to permanent.");

            // Persist & reload JSON to verify full DisplayProfiles round-trip!
            string cfgPath = Path.Combine(dir, "profiles.json");
            cfg.Save(cfgPath);
            cfg = AppConfig.Load(cfgPath);
            fLeft = cfg.Fences.Single(f => f.Id == "fence-left");
            fRight = cfg.Fences.Single(f => f.Id == "fence-right");

            // 2. Switch BACK to large screen (26x13): MUST restore EXACT original large-screen geometry,
            //    EXACT original member relative slots, EXACT original loose icon positions, AND keep new member "m4" inside fLeft!
            bool createdLargeAgain;
            var restoredLarge = DisplayProfileManager.SwitchOrAdaptProfile(cfg, largeAreas, m, 1f, out createdLargeAgain);
            Check(!createdLargeAgain && restoredLarge.Key == largeKey,
                "Returning to large screen must hit exact saved large-screen profile.");
            Check(fLeft.OuterCol == 1 && fLeft.OuterRow == 1 && fLeft.OuterCols == 6 && fLeft.OuterRows == 5,
                "fLeft must restore exact original large-screen bounds.");
            Check(fRight.OuterCol == 18 && fRight.OuterRow == 6 && fRight.OuterCols == 7 && fRight.OuterRows == 5,
                "fRight must restore exact original large-screen bounds.");

            var scrambledBackOnLarge = largeIcons.Concat(new[] { MakeIcon("m4", 0, 0, m, 10) })
                .Select((ic, idx) => MakeIcon(ic.Identity, 0, idx % 10, m, idx)).ToList();
            Dictionary<string, Point> largeTargets;
            DisplayProfileManager.PlanIconRestoration(cfg, restoredLarge, scrambledBackOnLarge, largeAreas, m, out largeTargets);
            Check(largeTargets["m1"] == new Point(2, 2) && largeTargets["m2"] == new Point(4, 2) && largeTargets["m3"] == new Point(3, 4),
                "fLeft original members must restore to their EXACT relative slots (including gaps)!");
            Check(fLeft.IsInInnerRect(largeTargets["m4"].X, largeTargets["m4"].Y),
                "New member m4 added on small screen must stay inside fLeft on large screen without displacing m1..m3!");
            Check(largeTargets["r1"] == new Point(19, 7) && largeTargets["r2"] == new Point(22, 7) &&
                  largeTargets["r3"] == new Point(20, 9) && largeTargets["r4"] == new Point(23, 9),
                "fRight members must restore to their EXACT original slots!");
            Check(largeTargets["loose-left"] == new Point(0, 0) &&
                  largeTargets["loose-br"] == new Point(25, 12) &&
                  largeTargets["loose-top"] == new Point(12, 0),
                "All loose desktop icons must restore to their EXACT original large-screen coordinates!");

            // 3. Switch back to small screen again: must recall user's customized small-screen placement (fLeft at 0,0)
            bool createdSmallAgain;
            DisplayProfileManager.SwitchOrAdaptProfile(cfg, smallAreas, m, 1f, out createdSmallAgain);
            Check(!createdSmallAgain && fLeft.OuterCol == 0 && fLeft.OuterRow == 0,
                "Returning to small screen must recall the user's customized small-screen layout.");

            // 4. Fuzzy +/-1 cell tolerance: minor taskbar/origin shift (25x13 instead of 26x13) must reuse large profile!
            var fuzzyLarge = new[] { new Rectangle(0, 0, 25, 13) };
            var matchedFuzzy = DisplayProfileManager.FindMatchingProfile(cfg, fuzzyLarge);
            Check(matchedFuzzy != null && matchedFuzzy.Key == largeKey,
                "A 1-cell origin/taskbar jitter must fuzzy-match the existing large-screen profile.");
        }

        private static void CheckDualToSingleConvergenceAndRestore()
        {
            var m = new DesktopGridMetrics { CellWidth = 96, CellHeight = 120, OriginX = 2, OriginY = 2 };
            var dualAreas = new[] { new Rectangle(0, 0, 14, 8), new Rectangle(14, 0, 22, 12) };
            var singleAreas = new[] { new Rectangle(0, 0, 14, 8) };

            var cfg = new AppConfig();
            var fPrimary = new FenceConfig
            {
                Id = "f-pri", Title = "主屏区", OuterCol = 1, OuterRow = 1, OuterCols = 5, OuterRows = 4,
                MemberIconIds = new List<string> { "p1", "p2" }
            };
            var fSecondary = new FenceConfig
            {
                Id = "f-sec", Title = "副屏区", OuterCol = 20, OuterRow = 2, OuterCols = 6, OuterRows = 5,
                MemberIconIds = new List<string> { "s1", "s2", "s3" }
            };
            cfg.Fences.Add(fPrimary);
            cfg.Fences.Add(fSecondary);

            var dualIcons = new List<DesktopIconInfo>
            {
                MakeIcon("p1", 2, 2, m, 0),
                MakeIcon("p2", 3, 2, m, 1),
                MakeIcon("s1", 21, 3, m, 2),
                MakeIcon("s2", 22, 3, m, 3),
                MakeIcon("s3", 23, 5, m, 4),
                MakeIcon("loose-sec", 34, 10, m, 5), // far bottom-right on secondary monitor
            };

            DisplayProfileManager.CaptureCurrentProfile(cfg, dualAreas, dualIcons, m, true);

            // Disconnect secondary monitor -> Strategy A: fSecondary MUST converge onto singleAreas[0] without overlapping fPrimary!
            bool createdSingle;
            var singleProf = DisplayProfileManager.SwitchOrAdaptProfile(cfg, singleAreas, m, 1f, out createdSingle);
            Check(createdSingle && singleAreas[0].Contains(new Rectangle(fPrimary.OuterCol, fPrimary.OuterRow, fPrimary.OuterCols, fPrimary.OuterRows)) &&
                  singleAreas[0].Contains(new Rectangle(fSecondary.OuterCol, fSecondary.OuterRow, fSecondary.OuterCols, fSecondary.OuterRows)),
                "Disconnecting secondary monitor must converge secondary fence onto remaining single screen.");
            Check(!FenceManager.ZonesOverlap(fPrimary.OuterCol, fPrimary.OuterRow, fPrimary.OuterCols, fPrimary.OuterRows,
                fSecondary.OuterCol, fSecondary.OuterRow, fSecondary.OuterCols, fSecondary.OuterRows, m, 1f),
                "Converged secondary fence must not overlap primary fence.");
            Check(fSecondary.OuterCol >= fPrimary.OuterCol,
                "Secondary (right-monitor) fence should converge toward the right side of the single screen.");

            Dictionary<string, Point> singleTargets;
            DisplayProfileManager.PlanIconRestoration(cfg, singleProf, dualIcons, singleAreas, m, out singleTargets);
            Check(fSecondary.MemberIconIds.All(id => fSecondary.IsInInnerRect(singleTargets[id].X, singleTargets[id].Y)),
                "All secondary-monitor members must remain accessible inside converged fence on single screen.");
            Check(singleAreas[0].Contains(singleTargets["loose-sec"]) &&
                  !fPrimary.IsInOuterRect(singleTargets["loose-sec"].X, singleTargets["loose-sec"].Y) &&
                  !fSecondary.IsInOuterRect(singleTargets["loose-sec"].X, singleTargets["loose-sec"].Y),
                "Secondary-monitor loose icon must adapt cleanly onto single screen outside all fences.");

            // Reconnect secondary monitor -> fSecondary, its members, and loose-sec MUST return to exact secondary-monitor spots!
            bool createdDualAgain;
            var restoredDual = DisplayProfileManager.SwitchOrAdaptProfile(cfg, dualAreas, m, 1f, out createdDualAgain);
            Check(!createdDualAgain && fSecondary.OuterCol == 20 && fSecondary.OuterRow == 2 &&
                  fSecondary.OuterCols == 6 && fSecondary.OuterRows == 5,
                "Reconnecting secondary monitor must restore secondary fence to exact original monitor & bounds.");
            Dictionary<string, Point> dualTargets;
            DisplayProfileManager.PlanIconRestoration(cfg, restoredDual, dualIcons, dualAreas, m, out dualTargets);
            Check(dualTargets["s1"] == new Point(21, 3) && dualTargets["s3"] == new Point(23, 5) &&
                  dualTargets["loose-sec"] == new Point(34, 10),
                "Reconnecting secondary monitor must restore secondary members and loose icons to exact original cells.");
        }

        private static void CheckTinyScreenOverflowAndAutoPruning()
        {
            var m = new DesktopGridMetrics { CellWidth = 96, CellHeight = 120, OriginX = 2, OriginY = 2 };
            var largeAreas = new[] { new Rectangle(0, 0, 20, 12) };
            var tinyAreas = new[] { new Rectangle(0, 0, 4, 4) }; // Only 2x2 = 4 inner slots max!

            var cfg = new AppConfig();
            var fence = new FenceConfig { Id = "big", OuterCol = 2, OuterRow = 2, OuterCols = 6, OuterRows = 5 }; // 4x3 = 12 slots
            var icons = new List<DesktopIconInfo>();
            for (int i = 0; i < 12; i++)
            {
                string id = "ic-" + i;
                fence.MemberIconIds.Add(id);
                icons.Add(MakeIcon(id, 3 + (i % 4), 3 + (i / 4), m, i));
            }
            cfg.Fences.Add(fence);
            DisplayProfileManager.CaptureCurrentProfile(cfg, largeAreas, icons, m, true);

            // Switch to ultra-tiny 4x4 screen: membership list MUST keep all 12 items intact!
            bool createdTiny;
            var tinyProf = DisplayProfileManager.SwitchOrAdaptProfile(cfg, tinyAreas, m, 1f, out createdTiny);
            Check(fence.MemberIconIds.Count == 12, "Extreme tiny screen must NEVER drop MemberIconIds.");
            Dictionary<string, Point> tinyTargets;
            DisplayProfileManager.PlanIconRestoration(cfg, tinyProf, icons, tinyAreas, m, out tinyTargets);
            Check(tinyTargets.Count == 12, "All 12 icons must be safely accounted for on tiny screen.");

            // Visit 12 temporary resolutions -> auto-generated profiles must be pruned while user-edited large profile survives!
            for (int k = 0; k < 12; k++)
            {
                bool c;
                DisplayProfileManager.SwitchOrAdaptProfile(cfg, new[] { new Rectangle(0, 0, 10 + k * 2, 7 + (k % 3)) }, m, 1f, out c);
            }
            int autoCount = cfg.DisplayProfiles.Values.Count(p => p.AutoGenerated);
            Check(autoCount <= 9, "Auto-generated temporary profiles must be pruned to avoid config bloat. Count=" + autoCount);
            Check(DisplayProfileManager.FindMatchingProfile(cfg, largeAreas) != null,
                "User-edited large profile must NEVER be evicted by temporary resolutions.");

            // Return to large screen -> all 12 members restore to exact original slots!
            bool createdLarge;
            var restoredLarge = DisplayProfileManager.SwitchOrAdaptProfile(cfg, largeAreas, m, 1f, out createdLarge);
            Check(!createdLarge && fence.OuterCols == 6 && fence.OuterRows == 5,
                "Returning to large screen after tiny/temp resolutions must restore original fence geometry.");
            Dictionary<string, Point> largeTargets;
            DisplayProfileManager.PlanIconRestoration(cfg, restoredLarge, icons, largeAreas, m, out largeTargets);
            for (int i = 0; i < 12; i++)
            {
                Point expected = new Point(3 + (i % 4), 3 + (i / 4));
                Check(largeTargets["ic-" + i] == expected,
                    "All 12 members including previously overflowed ones must return to exact original slots!");
            }
        }

        private static void CheckNativePrivateDesktopRestore(string dir)
        {
            var paths = new[] { "One", "Two", "Three", "LooseA", "LooseB" }
                .Select(n => Path.Combine(dir, "dp_" + n + ".txt")).ToArray();
            foreach (string p in paths) File.WriteAllText(p, nContent(p));

            PrivateDesktopView.OnPrivateDesktop(delegate
            {
                const int cell = 64;
                using (var host = new Form { FormBorderStyle = FormBorderStyle.None, StartPosition = FormStartPosition.Manual,
                    Bounds = new Rectangle(0, 0, 1280, 520), AutoScaleMode = AutoScaleMode.None, ShowInTaskbar = false })
                using (var panel = new Panel { Dock = DockStyle.Fill })
                using (var view = new PrivateDesktopView(paths))
                using (var controller = new DesktopIconController())
                {
                    host.Controls.Add(panel);
                    panel.Controls.Add(view);
                    host.Show();
                    view.SetSnap(false);
                    NativeMethods.SendMessage(view.Handle, 0x1000 + 53, IntPtr.Zero, new IntPtr(cell | (cell << 16)));
                    view.SetWorkArea(new Rectangle(0, 0, 1280, 520));
                    int[] cols = { 3, 5, 4, 0, 14 };
                    int[] rows = { 2, 2, 3, 0, 5 };
                    for (int i = 0; i < paths.Length; i++)
                        view.Items[i].Position = new Point(cell * cols[i] + 8, cell * rows[i] + 8);
                    view.SetSnap(true);

                    Check(controller.BindHandles(host.Handle, panel.Handle, view.Handle), "Bind private ListView.");
                    typeof(DesktopIconController).GetField("_shellView", Instance).SetValue(controller, new DesktopShellView(view));
                    var icons = controller.GetAllIcons();
                    var grid = controller.GetGridMetrics(icons);

                    var cfg = new AppConfig();
                    var fence = new FenceConfig
                    {
                        Id = "native-f1", OuterCol = 2, OuterRow = 1, OuterCols = 5, OuterRows = 4,
                        MemberIconIds = icons.Take(3).Select(i => i.Identity).ToList()
                    };
                    cfg.Fences.Add(fence);
                    var areas = new[] { new Rectangle(0, 0, 18, 7) };
                    DisplayProfileManager.CaptureCurrentProfile(cfg, areas, icons, grid, true);
                    var profile = cfg.DisplayProfiles[cfg.ActiveProfileKey];

                    // Simulate Windows Explorer scrambling all 5 icons to column 0 on display change!
                    view.SetSnap(false);
                    for (int i = 0; i < paths.Length; i++)
                        view.Items[i].Position = new Point(8, cell * i + 8);
                    view.SetSnap(true);

                    var mgr = (FenceManager)FormatterServices.GetUninitializedObject(typeof(FenceManager));
                    typeof(FenceManager).GetField("<Config>k__BackingField", Instance).SetValue(mgr, cfg);
                    typeof(FenceManager).GetField("_controller", Instance).SetValue(mgr, controller);
                    typeof(FenceManager).GetField("_attachedGeneration", Instance).SetValue(mgr, controller.HostGeneration);
                    typeof(FenceManager).GetField("_knownIconCells", Instance).SetValue(mgr, new Dictionary<string, Point>(StringComparer.OrdinalIgnoreCase));
                    typeof(FenceManager).GetField("_sessionClock", Instance).SetValue(mgr, System.Diagnostics.Stopwatch.StartNew());
                    typeof(FenceManager).GetField("_exiting", Instance).SetValue(mgr, true);

                    var scrambled = controller.GetAllIcons();
                    mgr.RestoreIconsForProfileAtomic(profile, scrambled, areas, grid, true);

                    var restored = controller.GetAllIcons();
                    for (int i = 0; i < paths.Length; i++)
                    {
                        var ic = restored.Single(x => x.Identity == icons[i].Identity);
                        Check(ic.GridCol(grid) == cols[i] && ic.GridRow(grid) == rows[i],
                            "Native ListView icon " + i + " must restore to (" + cols[i] + "," + rows[i] + "), got (" + ic.GridCol(grid) + "," + ic.GridRow(grid) + ")");
                    }
                    Check(controller.GetGridMetrics(restored).SnapToGridEnabled,
                        "Atomic profile restoration must cleanly restore LVS_EX_SNAPTOGRID.");
                }
            });
        }

        private static string nContent(string path) { return Path.GetFileName(path); }

        internal static void Run(string dir)
        {
            CheckLargeSmallRoundTripAndLooseIcons(dir);
            CheckDualToSingleConvergenceAndRestore();
            CheckTinyScreenOverflowAndAutoPruning();
            CheckNativePrivateDesktopRestore(dir);
        }
